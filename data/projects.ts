export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((project) => project.slug === slug);
}

export function getProjectMark(project: Project): string {
  if (project.mark) return project.mark;
  const letter = project.title.trim().charAt(0);
  return letter ? letter.toUpperCase() : "?";
}

export function getProjectPosition(slug: string) {
  const index = projects.findIndex((project) => project.slug === slug);
  const total = projects.length;
  const next = projects[(index + 1) % total];
  return { index, total, next };
}

export function getCategoryLabel(slug: string): string {
  return workCategories.find((category) => category.slug === slug)?.label ?? slug;
}

export function getProjectCategoryLabels(project: Project): string[] {
  return project.categories.map(getCategoryLabel);
}

export function filterProjectsByCategory(
  categorySlug: string,
  list: Project[] = projects,
): Project[] {
  if (categorySlug === "all") return list;
  return list.filter((project) => project.categories.includes(categorySlug));
}

